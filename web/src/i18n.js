export const dictionaries = { vi, en };

function detect() {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (LANGS.includes(stored)) return stored;
  } catch {}
  const nav = globalThis.navigator ?? {};
  const prefs = nav.languages?.length ? nav.languages : [nav.language || 'vi'];
  return prefs.some((l) => /^vi\b/i.test(l)) ? 'vi' : 'en';
}

const hasDom = typeof document !== 'undefined';
let lang = detect();
if (hasDom) document.documentElement.lang = lang;

export function getLang() {
  return lang;
}

export function t(key, params) {
  let text = dictionaries[lang][key] ?? vi[key] ?? key;
  if (params) text = text.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? '').toString());
  return text;
}

export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':').map((x) => x.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  }
  document.documentElement.classList.remove('i18n-pending');
}

export function setLang(next) {
  if (!LANGS.includes(next) || next === lang) return;
  lang = next;
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {}
  document.documentElement.lang = next;
  applyI18n();
  window.dispatchEvent(new CustomEvent('langchange', { detail: next }));
}
